"""Manifest + generated FreeCAD macro for the standalone export.

The manifest is the stable hand-off format.  The generated macro can be run in
FreeCAD (Macro -> Execute macro) and builds a FreeCAD document with one named
Part feature per exported object, including colours and custom metadata.
"""

from __future__ import annotations

import json
import os
import subprocess
from pathlib import Path
from typing import Any

from app.platform_tools import default_freecad_gui, freecad_gui_candidates

from .step_export import find_freecad_cmd

MANIFEST_SCHEMA = "visualopenems.discretized.v1"

DEFAULT_FREECAD = default_freecad_gui()

MACRO_TEMPLATE = r'''# -*- coding: utf-8 -*-
"""FreeCAD import macro generated by VisualopenEMS Discretized Export.

Run this file in FreeCAD:
    Macro -> Execute macro... -> select this file

It reads the adjacent manifest and builds one named Part feature per object.
A .FCStd file is written next to the manifest.
"""

from __future__ import annotations

import json
from pathlib import Path

import FreeCAD as App
import Mesh
import Part

try:
    BASE = Path(__file__).resolve().parent
except NameError:
    BASE = Path(r"__BASE_DIR__")

MANIFEST = BASE / "__MANIFEST_NAME__"


def _add_prop(obj, prop_type, name, value):
    try:
        if name not in obj.PropertiesList:
            obj.addProperty(prop_type, name, "VisualOpenEMS", name)
        setattr(obj, name, value)
    except Exception as exc:
        print(f"WARNING: could not set {name}: {exc}")


def _make_shape(mesh, name):
    if not mesh.CountFacets:
        raise ValueError("STL has no facets")
    shape = Part.Shape()
    shape.makeShapeFromMesh(mesh.Topology, 0.0)
    if shape.isClosed():
        try:
            shape = Part.makeSolid(shape)
        except Exception as exc:
            print(f"WARNING: makeSolid failed for {name}: {exc}")
    return shape


def main():
    if not MANIFEST.is_file():
        raise SystemExit(f"Manifest not found: {MANIFEST}")
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    objects = data.get("objects") or []
    project = str(data.get("project") or "project")
    mode = str(data.get("fcstd_object_type") or "part").lower()

    doc = App.newDocument(f"{project}_discretized")
    group = doc.addObject("App::DocumentObjectGroup", "VisualOpenEMS")
    group.Label = "VisualOpenEMS"

    built = 0
    for index, item in enumerate(objects):
        name = str(item.get("name") or f"object_{index + 1}")
        stl_rel = str(item.get("stl") or "")
        stl_path = BASE / stl_rel
        if not stl_path.is_file():
            print(f"WARNING: {name}: STL not found: {stl_path}")
            continue
        try:
            mesh = Mesh.Mesh(str(stl_path))
            if not mesh.CountFacets:
                raise ValueError("STL has no facets")
            if mode == "mesh":
                feature = doc.addObject("Mesh::Feature", f"vo_object_{index}")
                feature.Mesh = mesh
            else:
                feature = doc.addObject("Part::Feature", f"vo_object_{index}")
                feature.Shape = _make_shape(mesh, name)
        except Exception as exc:
            print(f"WARNING: {name}: could not build object: {exc}")
            continue
        feature.Label = name

        color = item.get("color") or [0.8, 0.5, 0.2, 1.0]
        try:
            if feature.ViewObject is not None and len(color) >= 3:
                feature.ViewObject.ShapeColor = tuple(float(c) for c in color[:3])
                feature.ViewObject.Transparency = int(item.get("transparency", 0))
        except Exception as exc:
            print(f"WARNING: {name}: colour not set: {exc}")

        _add_prop(feature, "App::PropertyString", "VOMaterial", str(item.get("material") or ""))
        _add_prop(feature, "App::PropertyString", "VOMaterialKind", str(item.get("kind") or ""))
        _add_prop(feature, "App::PropertyInteger", "VOCells", int(item.get("cells", 0) or 0))
        _add_prop(feature, "App::PropertyFloat", "VOVolume_mm3", float(item.get("volume_mm3", 0.0) or 0.0))
        _add_prop(feature, "App::PropertyString", "VOExactness", str(data.get("exactness") or ""))
        _add_prop(feature, "App::PropertyString", "VOSourceProject", project)

        group.addObject(feature)
        built += 1
        print(f"Imported {name} ({item.get('cells', 0)} cells)")

    grid_info = data.get("voxel_grid") or {}
    if grid_info:
        grid_file = BASE / str(grid_info.get("file") or "")
        if not grid_file.is_file():
            print(f"WARNING: voxel grid file not found: {grid_file}")
        else:
            try:
                grid_data = json.loads(grid_file.read_text(encoding="utf-8"))
                edges = []
                for line in grid_data.get("edges") or []:
                    if len(line) < 6:
                        continue
                    edges.append(
                        Part.LineSegment(
                            App.Vector(float(line[0]), float(line[1]), float(line[2])),
                            App.Vector(float(line[3]), float(line[4]), float(line[5])),
                        ).toShape()
                    )
                if edges:
                    grid_obj = doc.addObject("Part::Feature", "OpenEMS_Voxel_Grid")
                    grid_obj.Shape = Part.Compound(edges)
                    grid_obj.Label = "OpenEMS Voxel Grid"
                    try:
                        if grid_obj.ViewObject is not None:
                            grid_obj.ViewObject.LineColor = (0.1, 0.7, 1.0)
                            grid_obj.ViewObject.LineWidth = 1.0
                    except Exception as exc:
                        print(f"WARNING: voxel grid display not set: {exc}")
                    _add_prop(
                        grid_obj,
                        "App::PropertyString",
                        "VOKind",
                        "voxel_grid",
                    )
                    _add_prop(
                        grid_obj,
                        "App::PropertyString",
                        "VOGridMode",
                        str(grid_info.get("mode") or "boundary"),
                    )
                    group.addObject(grid_obj)
                    print(f"Imported OpenEMS voxel grid ({len(edges)} edges)")
            except Exception as exc:
                print(f"WARNING: voxel grid import failed: {exc}")

    if not built:
        raise SystemExit("No object could be imported")

    doc.recompute()
    try:
        import FreeCADGui as Gui
        if Gui.ActiveDocument is not None and Gui.ActiveDocument.ActiveView is not None:
            Gui.ActiveDocument.ActiveView.fitAll()
    except Exception:
        pass

    out_fcstd = BASE / f"{project}_discretized.FCStd"
    try:
        doc.saveAs(str(out_fcstd))
        print(f"FCStd written: {out_fcstd}")
    except Exception as exc:
        print(f"WARNING: could not save FCStd: {exc}")

    print(f"VisualOpenEMS import finished: {built}/{len(objects)} objects")


main()
'''


def write_manifest(
    path: str | Path,
    *,
    project: str,
    unit: str,
    cell_constant_material: bool,
    exactness: str,
    step: str | None,
    objects: list[dict[str, Any]],
    fcstd_object_type: str = "part",
    voxel_grid: dict[str, Any] | None = None,
) -> Path:
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    data = {
        "schema": MANIFEST_SCHEMA,
        "project": project,
        "unit": unit,
        "cell_constant_material": bool(cell_constant_material),
        "exactness": exactness,
        "step": step,
        "fcstd_object_type": fcstd_object_type,
        "voxel_grid": voxel_grid,
        "objects": objects,
    }
    out.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    return out


def write_macro(macro_path: str | Path, manifest_path: str | Path) -> Path:
    out = Path(macro_path)
    manifest = Path(manifest_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    text = (
        MACRO_TEMPLATE.replace("__BASE_DIR__", str(manifest.parent.resolve()))
        .replace("__MANIFEST_NAME__", manifest.name)
    )
    out.write_text(text, encoding="utf-8")
    return out


def find_freecad_exe(explicit: str | Path | None = None) -> Path | None:
    candidates: list[Path] = []
    if explicit:
        candidates.append(Path(explicit).expanduser())
    env = os.environ.get("FREECAD_EXE")
    if env:
        candidates.append(Path(env).expanduser())
    candidates.extend(freecad_gui_candidates())
    for candidate in candidates:
        try:
            if candidate.is_file():
                return candidate
        except OSError:
            continue
    return None


def build_fcstd(
    macro_path: str | Path,
    expected_fcstd: str | Path,
    *,
    freecad_cmd: str | Path | None = None,
    timeout: int = 900,
) -> tuple[bool, str, list[str]]:
    """Run the generated macro with FreeCADCmd and produce the .FCStd file."""
    macro = Path(macro_path).expanduser().resolve()
    expected = Path(expected_fcstd).expanduser().resolve()
    if not macro.is_file():
        return False, "macro not found", [f"FCStd not written: macro not found: {macro}"]
    cmd = find_freecad_cmd(freecad_cmd)
    if cmd is None:
        return (
            False,
            "FreeCADCmd not found",
            [
                "FCStd not written: FreeCADCmd not found. Set the FreeCADCmd "
                "path or the FREECAD_CMD environment variable."
            ],
        )

    kwargs: dict[str, Any] = {}
    if os.name == "nt":
        kwargs["creationflags"] = getattr(subprocess, "CREATE_NO_WINDOW", 0)
    try:
        proc = subprocess.run(
            [str(cmd), str(macro)],
            cwd=str(macro.parent),
            capture_output=True,
            text=True,
            timeout=timeout,
            **kwargs,
        )
    except subprocess.TimeoutExpired:
        return False, "FreeCADCmd timed out", [f"FCStd not written: timeout after {timeout}s"]
    except OSError as exc:
        return False, f"could not start FreeCADCmd: {exc}", [f"FCStd not written: {exc}"]

    log = (proc.stdout or "") + ("\n" + proc.stderr if proc.stderr else "")
    warnings: list[str] = []
    for line in log.splitlines():
        if line.startswith("WARNING: "):
            warnings.append("FCStd: " + line[len("WARNING: ") :].strip())
    if proc.returncode != 0:
        return False, log, warnings + [f"FCStd not written (FreeCADCmd exit {proc.returncode})"]
    if not expected.is_file() or expected.stat().st_size == 0:
        return False, log, warnings + [f"FCStd not written: {expected} is missing or empty"]
    return True, log, warnings


def open_in_freecad(
    path: str | Path, freecad_exe: str | Path | None = None
) -> tuple[bool, str]:
    """Open a STEP or FCStd file in the FreeCAD GUI."""
    target = Path(path).expanduser().resolve()
    if not target.is_file():
        return False, f"File not found: {target}"
    if target.suffix.lower() not in {".step", ".stp", ".fcstd"}:
        return False, f"Unsupported FreeCAD file type: {target.suffix}"
    exe = find_freecad_exe(freecad_exe)
    if exe is None:
        return False, "FreeCAD GUI binary not found. Set the FreeCAD GUI path."
    kwargs: dict[str, Any] = {}
    if os.name == "nt":
        kwargs["creationflags"] = getattr(subprocess, "CREATE_NO_WINDOW", 0)
    try:
        subprocess.Popen([str(exe), str(target)], **kwargs)
    except OSError as exc:
        return False, f"Could not start FreeCAD: {exc}"
    return True, f"Opened in FreeCAD: {target}"
